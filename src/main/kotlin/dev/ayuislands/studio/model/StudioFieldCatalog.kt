/** Field ownership and types; defaults remain in the original source state constructors. */
internal object StudioFieldCatalog {
    val fields: StudioList<StudioFieldDefinition> =
        StudioList(
            fieldGroups.flatMap { group ->
                group.names.map { name ->
                    StudioFieldDefinition(group.source, name, group.owner, group.type, xmlNames[name] ?: name)
                }
            },
        )
}
