internal enum class LegacyStore {
    SETTINGS,
    SYNTAX,
    MAPPINGS,
}

internal enum class StudioDomain {
    ACCENT,
    FONT,
    GLOW,
    SYNTAX,
    VCS,
}

internal enum class StudioFieldOwner(
    val domain: StudioDomain? = null,
) {
    ACCENT(StudioDomain.ACCENT),
    FONT(StudioDomain.FONT),
    GLOW(StudioDomain.GLOW),
    SYNTAX(StudioDomain.SYNTAX),
    VCS(StudioDomain.VCS),
    PLUGINS,
    WORKSPACE,
    SYSTEM,
    RUNTIME,
    RESOURCES,
    UI,
    MIGRATION,
    MAPPINGS,
}

internal data class StudioFieldDefinition(
    val source: LegacyStore,
    val name: String,
    val owner: StudioFieldOwner,
    val type: LegacyValueType,
    val xmlName: String = name,
)

